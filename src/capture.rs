/// What was scanned of a transcript (`.kontext/capture/<hash>.json`).
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
struct Mark {
    transcript: String,
    /// Up to which byte it was scanned.
    offset: u64,
    /// When it was first seen (ms): older answers are not written.
    since_ms: i64,
    /// Ids already written (`tool_use_id`, `prompt_id`), the last ones.
    seen: Vec<String>,
}

impl Mark {
    fn saw(&self, key: &str) -> bool {
        self.seen.iter().any(|s| s == key)
    }

    fn see(&mut self, key: String) {
        self.seen.push(key);
        if self.seen.len() > SEEN_MAX {
            let extra = self.seen.len() - SEEN_MAX;
            self.seen.drain(..extra);
        }
    }
}

fn state_dir(home: &Path) -> PathBuf {
    config::internal_dir(home).join("capture")
}

fn mark_path(home: &Path, transcript: &Path) -> PathBuf {
    let h = crate::model::sha256_hex(transcript.to_string_lossy().as_bytes());
    state_dir(home).join(format!("{}.json", &h[..32]))
}

fn load_mark(home: &Path, transcript: &Path) -> Option<Mark> {
    let text = fs::read_to_string(mark_path(home, transcript)).ok()?;
    serde_json::from_str(&text).ok()
}

fn save_mark(home: &Path, transcript: &Path, m: &Mark) -> Result<()> {
    fs::create_dir_all(state_dir(home))?;
    config::write_atomic(
        &mark_path(home, transcript),
        (serde_json::to_string(m)? + "\n").as_bytes(),
    )?;
    crate::hook::prune_older(&state_dir(home), STATE_DAYS);
    Ok(())
}

/// The answers the transcript gained since the mark, and the mark moved on.
/// The first time (no mark), it starts at the transcript's end, or at 0 if
/// the file does not exist yet (the first prompt of a session); answers older
/// than that first sight are never written. A transcript shorter than its
/// mark starts again from its end.
fn scan(tp: &Path, prev: Option<Mark>, now_ms: i64) -> Result<(Mark, Vec<Answered>)> {
    let size = fs::metadata(tp).ok().map(|m| m.len());
    let mut m = prev.unwrap_or_else(|| Mark {
        transcript: tp.display().to_string(),
        offset: size.unwrap_or(0),
        since_ms: now_ms,
        seen: Vec::new(),
    });
    let Some(size) = size else {
        return Ok((m, Vec::new()));
    };
    if size < m.offset {
        m.offset = size;
    }
    if size == m.offset {
        return Ok((m, Vec::new()));
    }
    let mut out = Vec::new();
    for (end, rec) in distill::read_lines_from(tp, m.offset)? {
        m.offset = end;
        let Some(a) = rec.as_ref().and_then(answered) else {
            continue;
        };
        if a.at_ms.is_some_and(|t| t < m.since_ms) || m.saw(&a.key) {
            continue;
        }
        m.see(a.key.clone());
        out.push(a);
    }
    Ok((m, out))
}

