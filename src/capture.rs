/// One `## <date> <HH:MM>` entry of a dump.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DumpEntry {
    /// `YYYY-MM-DD`, local: also the dump's name.
    pub date: String,
    /// `HH:MM`, local.
    pub time: String,
    /// The lines under `**Coordinator asked:**` (without `> `); none, no block.
    pub asked: Vec<String>,
    /// What goes under `**User:**`.
    pub user: String,
}

/// The local date and time of a moment, in ms.
pub fn local(ms: i64) -> (String, String) {
    let ts = Timestamp::from_millisecond(ms).unwrap_or_else(|_| Timestamp::now());
    let z = ts.to_zoned(TimeZone::system());
    (
        z.strftime("%Y-%m-%d").to_string(),
        z.strftime("%H:%M").to_string(),
    )
}

/// The text as the user wrote it, without blank lines around it.
fn clean(text: &str) -> String {
    text.trim_end()
        .trim_start_matches(['\n', '\r'])
        .replace("\r\n", "\n")
}

/// Where the capture-only pass leaves a secret: the distill's form, so its
/// key=value rule does not split the marker, and `redact_marked` swaps it
/// for [`SECRET_MARK`] with the rest.
const CAPTURE_REDACTED: &str = "[REDACTED:capture]";

/// `abc_` + 20 or more letters and digits (with a digit), a token with a
/// vendor prefix.
static VENDOR_TOKEN: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"\b[A-Za-z]{2,8}_[A-Za-z0-9]{20,}\b").unwrap());
/// `abc_` + a UUID.
static VENDOR_UUID: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(
        r"\b[A-Za-z]{2,8}_[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}\b",
    )
    .unwrap()
});
static SLACK: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"\bxox[abprs]-[A-Za-z0-9-]{10,}").unwrap());
/// A run of letters and digits (a hex secret must be one whole run).
static ALNUM_RUN: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"[0-9A-Za-z]+").unwrap());

/// The secrets the distill's redactor does not know, for the capture only:
/// vendor-prefixed tokens and UUIDs, Slack tokens, and 32-character hex
/// strings with a letter and a digit (account ids and API keys; a 40-character
/// git SHA or a 64-character hash is a longer run and stays).
pub fn redact_capture_only(text: &str) -> String {
    let t = VENDOR_UUID.replace_all(text, CAPTURE_REDACTED);
    let t = VENDOR_TOKEN.replace_all(&t, |c: &regex::Captures| {
        let tok = &c[0];
        let tail = tok.split_once('_').map(|(_, r)| r).unwrap_or("");
        if tail.chars().any(|ch| ch.is_ascii_digit()) {
            CAPTURE_REDACTED.to_string()
        } else {
            tok.to_string()
        }
    });
    let t = SLACK.replace_all(&t, CAPTURE_REDACTED);
    ALNUM_RUN
        .replace_all(&t, |c: &regex::Captures| {
            let run = &c[0];
            let hex = run.len() == 32
                && run.chars().all(|ch| ch.is_ascii_hexdigit())
                && run.chars().any(|ch| ch.is_ascii_digit())
                && run.chars().any(|ch| ch.is_ascii_alphabetic());
            if hex {
                CAPTURE_REDACTED.to_string()
            } else {
                run.to_string()
            }
        })
        .into_owned()
}

fn redact(text: &str) -> String {
    distill::redact_marked(&redact_capture_only(text), SECRET_MARK)
}

impl DumpEntry {
    /// A message the user typed, with the lines of the question it answers.
    pub fn typed(ms: i64, prompt: &str, asked: &[String]) -> DumpEntry {
        let (date, time) = local(ms);
        let asked = if asked.is_empty() {
            Vec::new()
        } else {
            redact(&asked.join("\n"))
                .lines()
                .map(str::to_string)
                .collect()
        };
        DumpEntry {
            date,
            time,
            asked,
            user: redact(&clean(prompt)),
        }
    }

    /// Answers to `AskUserQuestion`: numbered when there is more than one.
    pub fn answered(ms: i64, pairs: &[(String, String)]) -> DumpEntry {
        let (date, time) = local(ms);
        let numbered = pairs.len() > 1;
        let item = |i: usize, text: &str| -> Vec<String> {
            let text = redact(&clean(text));
            text.lines()
                .enumerate()
                .map(|(j, l)| match (numbered, j) {
                    (true, 0) => format!("{}. {l}", i + 1),
                    (true, _) if !l.is_empty() => format!("   {l}"),
                    _ => l.to_string(),
                })
                .collect()
        };
        let mut asked = Vec::new();
        let mut user = Vec::new();
        for (i, (q, a)) in pairs.iter().enumerate() {
            asked.extend(item(i, q));
            user.extend(item(i, a));
        }
        DumpEntry {
            date,
            time,
            asked,
            user: user.join("\n"),
        }
    }

    /// The entry in the skill's format, ending in one newline.
    pub fn render(&self) -> String {
        let mut s = format!("## {} {}\n\n", self.date, self.time);
        if !self.asked.is_empty() {
            s.push_str("**Coordinator asked:**\n\n");
            for l in &self.asked {
                if l.is_empty() {
                    s.push_str(">\n");
                } else {
                    s.push_str("> ");
                    s.push_str(l);
                    s.push('\n');
                }
            }
            s.push('\n');
        }
        s.push_str("**User:**\n\n");
        s.push_str(&self.user);
        s.push('\n');
        s
    }
}

/// The dump an entry of `date` of `add` bytes goes to: the last one of that
/// date, or the next (`<date>-2.md`, `-3`…) if it would pass
/// [`DUMP_MAX_BYTES`].
pub fn dump_file(dumps: &Path, date: &str, add: u64) -> Result<PathBuf> {
    let re = Regex::new(&format!(r"^{}(?:-(\d+))?\.md$", regex::escape(date)))?;
    let mut last: Option<u32> = None;
    if let Ok(rd) = fs::read_dir(dumps) {
        for ent in rd.flatten() {
            let name = ent.file_name().to_string_lossy().into_owned();
            if let Some(c) = re.captures(&name) {
                let n = c.get(1).and_then(|m| m.as_str().parse().ok()).unwrap_or(1);
                last = last.max(Some(n));
            }
        }
    }
    let name = |n: u32| {
        if n <= 1 {
            dumps.join(format!("{date}.md"))
        } else {
            dumps.join(format!("{date}-{n}.md"))
        }
    };
    Ok(match last {
        None => name(1),
        Some(n) => {
            let p = name(n);
            let len = fs::metadata(&p).map(|m| m.len()).unwrap_or(0);
            if len > 0 && len + add > DUMP_MAX_BYTES {
                name(n + 1)
            } else {
                p
            }
        }
    })
}

/// Appends an entry to its dump in `pm` (`.pm/`) in one write, with one blank
/// line before it if the file has text. The first time it creates `dumps/`,
/// it also writes `.pm/.gitignore` (`dumps/`) if there is none. Returns the
/// file and how many characters it wrote.
pub fn append(pm: &Path, e: &DumpEntry) -> Result<(PathBuf, usize)> {
    let dumps = pm.join("dumps");
    if !dumps.is_dir() {
        fs::create_dir_all(&dumps)?;
        if let Ok(mut f) = OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(pm.join(".gitignore"))
        {
            f.write_all(b"dumps/\n")?;
        }
    }
    let text = e.render();
    let path = dump_file(&dumps, &e.date, text.len() as u64 + 2)?;
    let mut f = OpenOptions::new()
        .create(true)
        .append(true)
        .read(true)
        .open(&path)?;
    let len = f.metadata()?.len();
    let sep = if len == 0 {
        ""
    } else {
        let back = len.min(2);
        let mut tail = vec![0u8; back as usize];
        f.seek(SeekFrom::Start(len - back))?;
        f.read_exact(&mut tail)?;
        if tail.ends_with(b"\n\n") || (len == 1 && tail == b"\n") {
            ""
        } else if tail.ends_with(b"\n") {
            "\n"
        } else {
            "\n\n"
        }
    };
    let out = format!("{sep}{text}");
    f.write_all(out.as_bytes())?;
    Ok((path, text.chars().count()))
}

