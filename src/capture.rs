//! The capture hook (DESIGN §12.3): writes each message the user sends to the
//! pm session, verbatim, into `.pm/dumps/<date>.md` of the code repo, in the
//! `kontext-pm` skill's format, with the question it answers. No model, no
//! ledger: it resolves the project, reads `[capture]`, and appends.
//!
//! - `user-prompt-submit` writes the typed prompt at once, from the payload's
//!   `prompt` (machine text is skipped: see [`skip_reason`]). The question it
//!   answers is the lines with `?` of the last assistant text in the
//!   transcript.
//! - Every trigger (`user-prompt-submit`, `stop`, `session-end`) scans what
//!   the transcript gained since last time for answers to the `AskUserQuestion`
//!   tool, and writes each one once.
//! - Off unless `[capture] enabled = true`, and with `KONTEXT_CAPTURE_DISABLE`.
//!   Only the `pm` role, never a sidechain entry, and not in a linked git
//!   worktree unless `[capture] worktrees = true`.
//! - The state (per transcript: how far it was scanned, when it was first
//!   seen, the ids already written) lives in `.kontext/capture/`, local, under
//!   `.kontext/capture.lock`. The first time a transcript is seen it starts at
//!   its end: nothing said before capture was on is written.
//! - It never prints anything: what it did goes in `hooks.log`, without any of
//!   the user's or the assistant's text.

