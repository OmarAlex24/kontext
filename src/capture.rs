/// If set to anything, the hook writes nothing.
pub const DISABLE_ENV: &str = "KONTEXT_CAPTURE_DISABLE";
/// What a secret becomes (the `kontext-pm` skill's marker).
pub const SECRET_MARK: &str = "[secret removed]";
/// A dump goes on in `<date>-2.md`, `-3`… when it would pass this.
pub const DUMP_MAX_BYTES: u64 = 60_000;
/// At most this many lines of the question are quoted (the last ones)…
pub const ASKED_MAX_LINES: usize = 20;
/// …and at most this many characters.
pub const ASKED_MAX_CHARS: usize = 2_000;
/// The tail of the transcript read first to find the last assistant text;
/// then 4×, 16×, 64× that.
const TAIL_FIRST: u64 = 1 << 20;
const TAIL_TRIES: u32 = 4;
/// Ids already written, per transcript.
const SEEN_MAX: usize = 256;
/// The state of a transcript is deleted after this many days without use.
const STATE_DAYS: u64 = 30;

/// Prompts that start with one of these (after leading whitespace) are
/// machine text, not something the human typed.
pub const MACHINE_PREFIXES: &[&str] = &[
    "<task-notification>",
    "[SYSTEM NOTIFICATION",
    "<system-reminder",
    "<cross-session-message",
    "<agent-message",
    "<local-command-",
    "<command-name>",
    "<command-message>",
    "<bash-input>",
    "<bash-stdout>",
    "Caveat: The messages below were generated by the user while running local commands",
    "[Request interrupted by user",
    // T3 Code posts these as user turns, with the same metadata as a typed
    // message: the reports of delegated agents and the updates of the pull
    // requests it watches. On a real project they were 4 of every 5 turns.
    "Delegated task node:",
    "Update on pull request #",
];

/// What `[capture]` says in project.toml.
#[derive(Debug, Clone, Default)]
pub struct Settings {
    pub enabled: bool,
    pub skip_prefixes: Vec<String>,
    /// Also capture in a linked git worktree (off: agents delegated into
    /// their own worktree are not the human, and those dumps die with it).
    pub worktrees: bool,
}

impl Settings {
    pub fn of(project: &Project) -> Settings {
        let c = project.capture.clone().unwrap_or_default();
        Settings {
            enabled: c.enabled,
            worktrees: c.worktrees,
            skip_prefixes: c
                .skip_prefixes
                .into_iter()
                .filter(|p| !p.trim().is_empty())
                .collect(),
        }
    }
}

/// Why a prompt is not written. Its description never carries the prompt.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Skip {
    Empty,
    SlashCommand,
    /// One of [`MACHINE_PREFIXES`].
    Machine(&'static str),
    /// One of `[capture] skip_prefixes`.
    Configured(String),
}

impl Skip {
    pub fn describe(&self) -> String {
        match self {
            Skip::Empty => "empty".into(),
            Skip::SlashCommand => "a slash command only".into(),
            Skip::Machine(p) => format!("starts with {p:?}"),
            Skip::Configured(p) => format!("starts with {p:?} from [capture] skip_prefixes"),
        }
    }
}

static SLASH: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"^/[\w:-]+$").unwrap());

/// `Some` if the prompt is machine text (or empty) and must not be written.
/// When in doubt it is written.
pub fn skip_reason(prompt: &str, extra: &[String]) -> Option<Skip> {
    let t = prompt.trim_start();
    if t.trim_end().is_empty() {
        return Some(Skip::Empty);
    }
    if let Some(p) = MACHINE_PREFIXES.iter().find(|p| t.starts_with(**p)) {
        return Some(Skip::Machine(p));
    }
    if let Some(p) = extra
        .iter()
        .find(|p| !p.trim().is_empty() && t.starts_with(p.as_str()))
    {
        return Some(Skip::Configured(p.clone()));
    }
    if SLASH.is_match(t.trim_end()) {
        return Some(Skip::SlashCommand);
    }
    None
}

/// The lines of an assistant message that ask something (they contain `?`),
/// verbatim: the last [`ASKED_MAX_LINES`], within [`ASKED_MAX_CHARS`].
pub fn asked_lines(text: &str) -> Vec<String> {
    let lines: Vec<&str> = text
        .lines()
        .map(str::trim_end)
        .filter(|l| l.contains('?'))
        .collect();
    let mut out: Vec<String> = Vec::new();
    let mut chars = 0;
    for l in lines.iter().rev() {
        if out.len() == ASKED_MAX_LINES {
            break;
        }
        let n = l.chars().count();
        if chars + n > ASKED_MAX_CHARS {
            if out.is_empty() {
                let cut: String = l.chars().take(ASKED_MAX_CHARS - 1).collect();
                out.push(cut + "…");
            }
            break;
        }
        chars += n;
        out.push(l.to_string());
    }
    out.reverse();
    out
}

fn kind(rec: &Value) -> Option<&str> {
    rec.get("type").and_then(Value::as_str)
}

/// An assistant entry of the main conversation (not a sidechain, not a
/// message Claude Code made up).
fn main_assistant(rec: &Value) -> bool {
    kind(rec) == Some("assistant")
        && !distill::flag(rec, "isSidechain")
        && rec
            .get("message")
            .and_then(|m| m.get("model"))
            .and_then(Value::as_str)
            != Some("<synthetic>")
}

fn message_id(rec: &Value) -> Option<&str> {
    rec.get("message")
        .and_then(|m| m.get("id"))
        .and_then(Value::as_str)
}

/// The text of the last assistant message in the transcript (all its text
/// blocks), reading only its tail: the last MB, then more if it has none.
pub fn last_assistant_text(path: &Path) -> Option<String> {
    let size = fs::metadata(path).ok()?.len();
    let mut span = TAIL_FIRST;
    for _ in 0..TAIL_TRIES {
        let start = size.saturating_sub(span);
        if let Some(t) = last_assistant_from(path, start) {
            return Some(t);
        }
        if start == 0 {
            return None;
        }
        span *= 4;
    }
    None
}

fn last_assistant_from(path: &Path, start: u64) -> Option<String> {
    // From the byte before `start`, the first line read is either the end of
    // the line before (`\n` alone) or a piece of one: it is dropped.
    let from = start.saturating_sub(1);
    let lines = distill::read_lines_from(path, from).ok()?;
    let skip = usize::from(start > 0);
    let recs: Vec<&Value> = lines
        .iter()
        .skip(skip)
        .filter_map(|(_, v)| v.as_ref())
        .collect();
    let i = recs
        .iter()
        .rposition(|r| main_assistant(r) && !distill::text_blocks(r).is_empty())?;
    let mut parts = vec![distill::text_blocks(recs[i])];
    // Claude Code writes one entry per block: earlier text blocks of the same
    // message, right before it, belong to it too.
    if let Some(id) = message_id(recs[i]) {
        for r in recs[..i].iter().rev() {
            if kind(r) == Some("user") {
                break;
            }
            if !main_assistant(r) {
                continue;
            }
            if message_id(r) != Some(id) {
                break;
            }
            let t = distill::text_blocks(r);
            if !t.is_empty() {
                parts.push(t);
            }
        }
    }
    parts.reverse();
    Some(parts.join("\n"))
}

/// An answer to the `AskUserQuestion` tool, found in the transcript.
#[derive(Debug, Clone, PartialEq)]
pub struct Answered {
    /// The `tool_use_id` (or the entry's `uuid`).
    pub key: String,
    pub at_ms: Option<i64>,
    /// `(question, answer)`, in question order, only the answered ones.
    pub pairs: Vec<(String, String)>,
}

fn answer_text(v: &Value) -> String {
    match v {
        Value::String(s) => s.clone(),
        Value::Array(xs) => xs
            .iter()
            .map(|x| match x {
                Value::String(s) => s.clone(),
                other => other.to_string(),
            })
            .collect::<Vec<_>>()
            .join(", "),
        Value::Null => String::new(),
        other => other.to_string(),
    }
}

/// The answers of a transcript entry, if it is a main-conversation `user`
/// entry whose `toolUseResult` has `questions` and `answers`.
pub fn answered(rec: &Value) -> Option<Answered> {
    if kind(rec) != Some("user") || distill::flag(rec, "isSidechain") {
        return None;
    }
    let tur = rec.get("toolUseResult")?.as_object()?;
    let questions = tur.get("questions")?.as_array()?;
    let answers = tur.get("answers")?.as_object()?;
    let mut pairs = Vec::new();
    for q in questions {
        let (text, header) = match q {
            Value::String(s) => (s.as_str(), None),
            Value::Object(o) => (
                o.get("question").and_then(Value::as_str).unwrap_or(""),
                o.get("header").and_then(Value::as_str),
            ),
            _ => continue,
        };
        if text.trim().is_empty() {
            continue;
        }
        let Some(a) = answers
            .get(text)
            .or_else(|| header.and_then(|h| answers.get(h)))
        else {
            continue;
        };
        let a = answer_text(a);
        if a.trim().is_empty() {
            continue;
        }
        pairs.push((text.to_string(), a));
    }
    if pairs.is_empty() {
        return None;
    }
    let tool_use_id = match rec.get("message").and_then(|m| m.get("content")) {
        Some(Value::Array(blocks)) => blocks.iter().find_map(|b| {
            (b.get("type").and_then(Value::as_str) == Some("tool_result"))
                .then(|| b.get("tool_use_id").and_then(Value::as_str))
                .flatten()
        }),
        _ => None,
    };
    let key = tool_use_id
        .or_else(|| rec.get("uuid").and_then(Value::as_str))
        .map(str::to_string)
        .unwrap_or_else(|| {
            let mut s = rec
                .get("timestamp")
                .and_then(Value::as_str)
                .unwrap_or("")
                .to_string();
            for (q, a) in &pairs {
                s.push_str(q);
                s.push_str(a);
            }
            format!("h:{}", &crate::model::sha256_hex(s.as_bytes())[..32])
        });
    let at_ms = rec
        .get("timestamp")
        .and_then(Value::as_str)
        .and_then(|t| t.parse::<Timestamp>().ok())
        .map(|t| t.as_millisecond());
    Some(Answered { key, at_ms, pairs })
}

